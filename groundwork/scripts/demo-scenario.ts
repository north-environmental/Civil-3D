/**
 * Runs the headline scenario (SPEC §10) through commands only, against the real server, and writes
 * docs/demo-summary.md plus screenshots in docs/screens/ (demo-*.png).
 *
 *   npm run demo                 # needs `npm run build` once (uses the built web app for renders)
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { headlineSteps } from '@groundwork/core';
import { startTestApp } from '../e2e/helpers';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

async function main() {
  const app = await startTestApp();
  const lines: string[] = ['# Headline demo scenario: command transcript', '', '_Generated by `npm run demo` (commands only; the same commands Claude sends over MCP)._', ''];
  const post = async (name: string, input: unknown, images = false) => {
    const res = await fetch(`${app.url}/api/commands/${name}${images ? '' : '?images=0'}`, { method: 'POST', headers: { 'content-type': 'application/json', 'x-groundwork-source': 'script' }, body: JSON.stringify(input) });
    return (await res.json()) as any;
  };
  let failed = 0;
  try {
    const t0 = Date.now();
    for (const st of headlineSteps()) {
      const t = Date.now();
      const r = await post(st.command, st.input);
      const ms = Date.now() - t;
      if (!r.ok) failed++;
      const summary = r.ok ? r.result.summary : `ERROR: ${r.error}`;
      console.log(`[step ${st.step}] ${st.command} (${ms} ms)\n    ${summary}\n`);
      lines.push(`### Step ${st.step}: ${st.label}`, '', '```', `${st.command} ${JSON.stringify(st.input)}`, '```', '', summary, '');
      if (r.ok && st.command === 'generate_layout') lines.push(`_Rationale:_ ${r.result.rationale}`, '', ...(r.result.notes as string[]).map((n: string) => `- ${n}`), '');
      if (r.ok && st.command === 'compare_scenarios') {
        const ids = r.result.scenarios.map((s: any) => s.id);
        lines.push(`| Metric | ${ids.join(' | ')} |`, `|---|${ids.map(() => '---').join('|')}|`, ...r.result.rows.map((row: any) => `| ${row.metric} | ${ids.map((id: string) => row.values[id]).join(' | ')} |`), '');
      }
    }
    const summary = await post('get_project_summary', {});
    lines.push('## Final state', '', summary.result.summary, '', '| Yield | Value | Limit / basis |', '|---|---|---|', ...summary.result.yield.map((y: any) => `| ${y.label} | ${y.value} | ${[y.limit, y.citation].filter(Boolean).join(' · ')} |`), '');
    const shots: [string, Record<string, unknown>][] = [
      ['demo-headline-plan.png', { view: 'plan' }],
      ['demo-headline-asbuilt.png', { view: 'plan', layers: ['asBuilt'], hide: ['existingContours'] }],
    ];
    for (const [file, input] of shots) {
      const r = await post('render_view', input, true);
      if (r.ok && r.result.image) fs.writeFileSync(path.join(root, 'docs', 'screens', file), Buffer.from(r.result.image.base64, 'base64'));
      else console.warn(`render ${file} failed: ${r.error ?? r.result?.imageError}`);
    }
    lines.push(`_Total: ${((Date.now() - t0) / 1000).toFixed(1)} s. Screenshots: docs/screens/demo-headline-plan.png, docs/screens/demo-headline-asbuilt.png._`, '');
    fs.writeFileSync(path.join(root, 'docs', 'demo-summary.md'), lines.join('\n'));
    console.log(`Wrote docs/demo-summary.md (${failed} failed step(s)).`);
  } finally {
    await app.close();
  }
  if (failed) process.exit(1);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
