/**
 * Project state: site + rules + scenarios + history. Plain JSON-serializable data except Site.dem.data.
 */
import type { Pt, Region, Ring } from '../geometry/basic';
import type { GradingCriteria } from '../criteria/grading';
import type { LayoutCriteria } from '../criteria/layout';
import type { StormwaterCriteria } from '../criteria/stormwater';
import type { ZoningRuleSet } from '../zoning/rules';
import type { Site } from './model';

export type Network = 'truck' | 'car' | 'emergency';
export type BuildingType = 'crossDock' | 'rearLoad';
/** Building sides in the building frame: u = along length, v = across depth. */
export type Side = '+u' | '-u' | '+v' | '-v';

export type Program = {
  buildingSf: number;
  buildingType: BuildingType;
  /** Optional explicit dimensions; otherwise depth comes from criteria and length from SF / depth. */
  lengthFt?: number;
  depthFt?: number;
  clearHeightFt: number;
  /** 'max' = as many as door spacing allows. */
  dockDoors: number | 'max';
  /** Target trailer stalls ('max' = as many as fit). */
  trailerStalls: number | 'max';
  /** Explicit car stall target; when absent it is derived from employees via the zoning ratios. */
  carStalls?: number;
  employeesLargestShift?: number;
  employeesTwoLargestShifts?: number;
  officeSf: number;
};

export type AccessSpec = {
  id: string;
  network: Network;
  /** Road name (matched case-insensitively against site roads, e.g. "Route 72"). */
  road: string;
  /** Station along the road frontage in ft from the frontage start, or 'auto'. */
  position: number | 'auto';
  lanes?: number;
  widthFt?: number;
};

export type Placement = {
  center: Pt;
  /** Angle of the building's long axis, degrees CCW from east. */
  rotationDeg: number;
  /** Which sides carry dock doors. */
  dockSides: Side[];
  /** Which side the car parking / office is on. */
  carSide: Side;
  /** How the placement was chosen, for the log. */
  source: 'explicit' | 'solver';
  alignedToRoad?: string;
};

type Base = {
  id: string;
  name: string;
  /** auto = regenerated by the layout engine; manual objects persist through regeneration. */
  auto: boolean;
};

export type Building = Base & {
  type: 'building';
  center: Pt;
  rotationDeg: number;
  lengthFt: number;
  depthFt: number;
  areaSf: number;
  buildingType: BuildingType;
  dockSides: Side[];
  carSide: Side;
  clearHeightFt: number;
  heightFt: number;
  officeSf: number;
  doorsPerSide: number;
  dockDoors: number;
  polygon: Ring;
};
export type TruckCourt = Base & {
  type: 'truckCourt';
  buildingId: string;
  side: Side;
  depthFt: number;
  apronFt: number;
  trailerRow: boolean;
  trailerStalls: number;
  /** Court rectangle in the building frame: [u0, v0, u1, v1]. */
  uv: [number, number, number, number];
  polygon: Ring;
  /** Trailer stall row band in the building frame, when present. */
  trailerUv?: [number, number, number, number];
};
export type TruckApron = Base & {
  /** Truck pavement that is not a dock court (e.g. the end drive that links two courts). */
  type: 'truckApron';
  buildingId: string;
  polygon: Ring;
};
export type TrailerField = Base & {
  type: 'trailerField';
  center: Pt;
  rotationDeg: number;
  lengthFt: number;
  depthFt: number;
  rows: number;
  stalls: number;
  polygon: Ring;
};
export type ParkingRow = {
  /** Local v of the row's stall band start (band is stallLengthFt deep). */
  v0: number;
  /** +1 = stalls open toward +v (aisle on the +v side); -1 = aisle on the -v side. */
  aisleSide: 1 | -1;
  stalls: number;
  ada: number;
  van: number;
};
export type ParkingField = Base & {
  type: 'parkingField';
  /** Field frame: origin at the corner nearest the building; u along rows, v away from the building. */
  origin: Pt;
  angleDeg: number;
  lengthFt: number;
  depthFt: number;
  modules: number;
  rows: ParkingRow[];
  stallsStd: number;
  stallsAda: number;
  stallsVan: number;
  stallsTotal: number;
  islandSf: number;
  attachedTo?: { buildingId: string; side: Side };
  /** Design slope away from the anchor edge, percent. */
  slopePct: number;
  polygon: Ring;
};
export type Driveway = Base & {
  type: 'driveway';
  accessId?: string;
  network: Network;
  roadId: string;
  roadName: string;
  /** Point on the ROW line (parcel edge) at the driveway centerline. */
  position: Pt;
  /** Unit vector pointing into the site, perpendicular to the frontage. */
  inward: Pt;
  /** Distance along the road's frontage from its start, ft. */
  stationFt: number;
  widthFt: number;
  lanes: number;
  radiusFt: number;
  /** Distance to the nearest intersecting-street ROW line along the frontage, ft. */
  toIntersectionFt: number | null;
  polygon: Ring;
};
export type Drive = Base & {
  type: 'drive';
  network: Network;
  centerline: Pt[];
  widthFt: number;
  lengthFt: number;
  drivewayId?: string;
  toObjectId?: string;
  polygon: Region;
};
export type Basin = Base & {
  type: 'basin';
  polygon: Ring;
  areaSf: number;
  depthFt: number;
  freeboardFt: number;
  sideSlopeHtoV: number;
  storageCf: number;
  /** Top-of-berm elevation; null = derived from existing ground at grading time. */
  topElevFt: number | null;
  meanExistingElevFt: number;
};
export type LandscapeArea = Base & {
  type: 'landscape';
  kind: 'screen' | 'buffer' | 'strip';
  /** Building wall this strip screens, when applicable. */
  wallSide?: Side;
  polygon: Ring;
  areaSf: number;
  note: string;
};

export type DesignObject =
  | Building
  | TruckCourt
  | TruckApron
  | TrailerField
  | ParkingField
  | Driveway
  | Drive
  | Basin
  | LandscapeArea;
export type ObjectType = DesignObject['type'];

export type CheckStatus = 'pass' | 'fail' | 'warn' | 'n/a';
export type Check = {
  id: string;
  ruleId: string;
  group: 'zoning' | 'engineering' | 'grading';
  category: string;
  title: string;
  status: CheckStatus;
  /** Numeric value when applicable (units below). */
  value: number | null;
  limit: number | null;
  units: string;
  citation: string;
  objectIds: string[];
  message: string;
};

export type YieldRow = {
  key: string;
  label: string;
  value: number;
  units: string;
  /** Formatted value for display. */
  display: string;
  limit?: string;
  citation?: string;
};

export type EarthworkCategory = 'pad' | 'truckCourt' | 'parking' | 'drive' | 'basin' | 'tieIn';
export type RetainingWall = {
  id: string;
  lengthFt: number;
  maxHeightFt: number;
  avgHeightFt: number;
  /** Representative location (centroid of wall cells). */
  at: Pt;
  betweenObjectIds: string[];
  /** dockWing = the short return wall where the dock-height truck court meets the pad at a building corner (expected). */
  kind: 'retaining' | 'dockWing';
};
export type EarthworkReport = {
  ffeFt: number;
  gridCellFt: number;
  cutCy: number;
  fillCy: number;
  /** cut × (1 − shrink) − fill. Positive = surplus (export), negative = import. */
  netCy: number;
  shrinkPct: number;
  topsoilStripCy: number;
  disturbedAreaSf: number;
  /** Volume of pavement/slab sections removed from fill (finished grade → subgrade), CY. */
  sectionAdjustmentCy: number;
  byCategory: { category: EarthworkCategory; cutCy: number; fillCy: number; areaSf: number }[];
  /** Site retaining walls (dock wing walls are listed separately). */
  walls: RetainingWall[];
  dockWingWalls: RetainingWall[];
  wallTotalLengthFt: number;
  wallMaxHeightFt: number;
  offsiteAreaSf: number;
  offsiteMaxDeltaFt: number;
  maxCutFt: number;
  maxFillFt: number;
  feasibleFfe: { minFt: number; maxFt: number; binding: string[] } | null;
  balance?: { targetNetCy: number; achieved: boolean; note: string };
  drives: { id: string; name: string; gradePct: number; maxGradePct: number; startElevFt: number; endElevFt: number; lengthFt: number }[];
  spots: { label: string; at: Pt; elevFt: number }[];
  /** Slopes measured on the proposed grid: whole parking fields and their accessible stalls/aisles. */
  slopes: { id: string; name: string; kind: 'parking' | 'ada'; slopePct: number }[];
  /** Tie-in slope area steeper than the preferred (4:1) and maximum (3:1) slopes, SF. */
  steepTieInSf: { overPreferred: number; overMax: number };
};

export type Assumption = { key: string; label: string; value: string; source: string; changed: boolean };

export type ScenarioPrefs = {
  /** Road the long axis should parallel (solver hint). */
  alignToRoad?: string;
  rotationDeg?: number;
  /** Prefer dock walls that do not face residential districts. */
  docksAwayFromResidential: boolean;
  /** Add the trailer row opposite the docks in each truck court. */
  trailerRowInCourts: boolean;
  /** Ids of auto-generated objects hidden by delete_object until the layout is regenerated. */
  omit?: string[];
};

export type Scenario = {
  id: string;
  name: string;
  program: Program | null;
  access: AccessSpec[];
  prefs: ScenarioPrefs;
  placement: Placement | null;
  objects: DesignObject[];
  layoutCriteria: LayoutCriteria;
  stormwater: StormwaterCriteria;
  grading: {
    criteria: GradingCriteria;
    /** Finished floor elevation; null until grade_site / optimize_ffe has run. */
    ffeFt: number | null;
    graded: boolean;
    balanceTargetCy: number | null;
  };
  results: {
    yield: YieldRow[];
    earthwork: EarthworkReport | null;
    layoutNotes: string[];
  };
  checks: Check[];
  nextId: number;
};

export type DesignLogEntry = {
  seq: number;
  at: string;
  source: 'ui' | 'mcp' | 'script' | 'system';
  command: string;
  message: string;
  kind: 'action' | 'note';
  revision: number;
};

export type Snapshot = {
  site: Site | null;
  rules: ZoningRuleSet | null;
  scenarios: Scenario[];
  activeScenarioId: string;
};

export type Project = Snapshot & {
  id: string;
  name: string;
  revision: number;
  log: DesignLogEntry[];
  history: { past: Snapshot[]; future: Snapshot[] };
};

export function activeScenario(p: Project): Scenario {
  const s = p.scenarios.find((x) => x.id === p.activeScenarioId);
  if (!s) throw new Error(`Active scenario ${p.activeScenarioId} not found`);
  return s;
}
export function objectsOfType<T extends ObjectType>(s: Scenario, type: T): Extract<DesignObject, { type: T }>[] {
  return s.objects.filter((o) => o.type === type) as Extract<DesignObject, { type: T }>[];
}
export function replaceScenario(p: Project, s: Scenario): Project {
  return { ...p, scenarios: p.scenarios.map((x) => (x.id === s.id ? s : x)) };
}
