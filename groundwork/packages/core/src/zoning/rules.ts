/** Built-in rule sets by district code. Other jurisdictions arrive via set_zoning_rules. */
export const BUILTIN_RULESETS: Record<string, ZoningRuleSet> = { 'I-1': NORTH_LEBANON_I1 };

export function findRule(rules: ZoningRuleSet, key: string): ZoningRule | undefined {
  // Prefer confirmed rules; a proposed (unconfirmed) rule never overrides a confirmed one.
  return rules.rules.find((x) => x.key === key && x.confirmed) ?? rules.rules.find((x) => x.key === key);
}
export function ruleNumber(rules: ZoningRuleSet, key: string, fallback: number): number {
  const rule = findRule(rules, key);
  return rule && typeof rule.value === 'number' ? rule.value : fallback;
}
export function ruleTable(rules: ZoningRuleSet, key: string): Record<string, number> | undefined {
  const rule = findRule(rules, key);
  return rule && typeof rule.value === 'object' ? (rule.value as Record<string, number>) : undefined;
}
export function citationOf(rules: ZoningRuleSet, key: string): string {
  return findRule(rules, key)?.citation.section ?? '';
}

/** Loading berths required for a gross floor area (§ 27-1408 table), both rounding readings. */
export function loadingBerthsRequired(
  gfaSf: number,
  table: Record<string, number>,
): { conservative: number; roundedDown: number } {
  if (gfaSf <= 2000) return { conservative: table.upTo2000 ?? 0, roundedDown: table.upTo2000 ?? 0 };
  if (gfaSf <= 10000) return { conservative: table.upTo10000 ?? 1, roundedDown: table.upTo10000 ?? 1 };
  if (gfaSf <= (table.baseOverSf ?? 50000)) return { conservative: table.upTo50000 ?? 2, roundedDown: table.upTo50000 ?? 2 };
  const extra = (gfaSf - (table.baseOverSf ?? 50000)) / (table.perAdditionalSf ?? 40000);
  return { conservative: (table.base ?? 3) + Math.ceil(extra), roundedDown: (table.base ?? 3) + Math.floor(extra) };
}
