import { z } from 'zod';

export const RuleCategorySchema = z.enum([
  'setback',
  'coverage',
  'height',
  'lot',
  'parking',
  'loading',
  'landscape',
  'access',
  'grade',
  'use',
]);
export const RuleSchema = z.object({
  id: z.string(),
  /** Semantic key the engines understand (see RULE_KEYS). Unknown keys are kept and shown but not evaluated. */
  key: z.string(),
  district: z.string(),
  category: RuleCategorySchema,
  appliesTo: z.enum(['building', 'parking', 'loading', 'pavement', 'lot', 'driveway', 'landscape']),
  edgeCondition: z.enum(['front', 'side', 'rear', 'abutsResidential', 'acrossStreetFromResidential']).optional(),
  value: z.union([z.number(), z.record(z.number()), z.string()]),
  units: z.enum(['ft', 'pct', 'sf', 'ac', 'count', 'ratio', 'text']),
  operator: z.enum(['min', 'max', 'eq', 'table', 'text']),
  label: z.string(),
  citation: z.object({
    section: z.string(),
    source: z.enum(['ecode360', 'zoneomics', 'reference-doc', 'user']),
    url: z.string().optional(),
    quote: z.string(),
  }),
  interpretationFlags: z.array(z.string()).optional(),
  confirmed: z.boolean(),
});
export type ZoningRule = z.infer<typeof RuleSchema>;

export const RuleSetSchema = z.object({
  jurisdiction: z.string(),
  district: z.string(),
  districtName: z.string(),
  sourceNote: z.string(),
  rules: z.array(RuleSchema),
});
export type ZoningRuleSet = z.infer<typeof RuleSetSchema>;

